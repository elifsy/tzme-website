import assert from 'node:assert/strict'
import { createIndustrialQuality } from '../src/three/industrialQuality.js'

const quality = createIndustrialQuality({ pixelRatio: 2 })
quality.configure('orbit', 1000, 600)
assert.equal(quality.restore(), 1.7)
for (let time = 0; time < 1800; time += 16.67) quality.update(time, true)
assert.equal(quality.ratio, 1.5, 'Fast frames retain full moving quality')
console.log('PASS Fast frames retain their moving resolution')
for (let time = 2000; time < 6000; time += 50) quality.update(time, true)
assert.equal(quality.ratio, 1, 'Slow frames reduce the buffer without dropping below native CSS resolution')
console.log('PASS Sustained slow frames reduce buffer size within bounds')
quality.configure('inspect', 1000, 600)
assert.equal(quality.ratio, 1.25, 'Entering the lighter close-up recovers its own quality')
quality.configure('orbit', 1000, 600)
console.log('PASS Close-up restores detail after a demanding panorama')
assert.equal(quality.restore(), 1.7)
console.log('PASS Idle restores the original sharp resolution')
quality.update(0, true); quality.pause(); quality.update(120000, true)
assert.equal(quality.ratio, 1.5)
console.log('PASS Offscreen and background time cannot trigger a false quality drop')
quality.configure('inspect', 1000, 600)
assert.equal(quality.restore(), 1.25)
console.log('PASS Close-up retains its own rendering ceiling')
quality.configure('orbit', 4000, 2400); quality.restore()
assert.ok(4000 * 2400 * quality.ratio ** 2 <= 2400000 + .01)
console.log('PASS Very large viewports remain inside the pixel budget')
const mobile = createIndustrialQuality({ pixelRatio: 3, compact: true })
mobile.configure('orbit', 390, 450)
assert.equal(mobile.restore(), 1.5)
console.log('PASS Mobile resolution remains capped for high-density screens')
const native = createIndustrialQuality({ pixelRatio: 1 })
native.configure('orbit', 1000, 600)
for (let time = 0; time < 4000; time += 50) native.update(time, true)
assert.equal(native.ratio, 1)
console.log('PASS Normal-density screens keep native resolution')
